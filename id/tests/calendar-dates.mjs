import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { getOccurrence, eventOccursOn } from "../assets/calendar-dates.mjs";

process.env.TZ = "America/Los_Angeles";
const { events } = JSON.parse(readFileSync(new URL("../data/events.json", import.meta.url), "utf8"));
assert.equal(events.length, 124, "production table row count");
assert.equal(new Set(events.map(e => e.id)).size, 124, "stable unique event IDs");
assert.equal(new Set(events.map(e => e.nameEn)).size, 124, "no duplicate event names");
assert.ok(events.every(e => e.sourceUrl && /^https?:\/\//.test(e.sourceUrl)), "every event has a source URL");
assert.ok(events.every(e => e.date2026 && JSON.stringify(getOccurrence(e, 2026)) === JSON.stringify(e.date2026)), "all 2026 dates compute from the structured rule");
assert.ok(events.every(e => e.classification && ["un","unesco","campaign","national","other"].includes(e.classification)));
const months = new Set(events.map(e => Number(e.date2026.start.slice(5,7))));
assert.equal(months.size, 12, "all months represented");
const find = id => events.find(e => e.id === id);
const start = (id, year) => getOccurrence(find(id), year);
assert.deepEqual(start("world-whale-day", 2026), {start:"2026-02-15",end:"2026-02-15"});
assert.deepEqual(start("world-pangolin-day", 2026), {start:"2026-02-21",end:"2026-02-21"});
assert.deepEqual(start("world-pangolin-day", 2027), {start:"2027-02-20",end:"2027-02-20"});
assert.deepEqual(start("world-otter-day", 2026), {start:"2026-05-27",end:"2026-05-27"});
assert.deepEqual(start("world-otter-day", 2027), {start:"2027-05-26",end:"2027-05-26"});
assert.deepEqual(start("international-bat-night", 2026), {start:"2026-08-29",end:"2026-08-30"});
assert.deepEqual(start("international-bat-night", 2027), {start:"2027-08-28",end:"2027-08-29"});
assert.equal(eventOccursOn(find("international-bat-night"), new Date(2026,7,29)), true);
assert.equal(eventOccursOn(find("international-bat-night"), new Date(2026,7,30)), true);
assert.deepEqual(start("international-red-panda-day", 2026), {start:"2026-09-19",end:"2026-09-19"});
assert.deepEqual(start("world-lemur-day", 2026), {start:"2026-10-30",end:"2026-10-30"});
assert.deepEqual(start("world-lemur-day", 2027), {start:"2027-10-29",end:"2027-10-29"});
assert.deepEqual(start("national-bison-day", 2026), {start:"2026-11-07",end:"2026-11-07"});
assert.deepEqual(start("world-numbat-day", 2026), {start:"2026-11-07",end:"2026-11-07"});
assert.deepEqual(start("world-fish-migration-day", 2026), {start:"2026-05-23",end:"2026-05-23"});
assert.equal(start("world-fish-migration-day", 2027), null);
assert.deepEqual(start("world-migratory-bird-day-may", 2026), {start:"2026-05-09",end:"2026-05-09"});
assert.deepEqual(start("world-migratory-bird-day-october", 2026), {start:"2026-10-10",end:"2026-10-10"});
assert.deepEqual(start("world-migratory-bird-day-may", 2027), {start:"2027-05-08",end:"2027-05-08"});
assert.deepEqual(start("world-migratory-bird-day-october", 2027), {start:"2027-10-09",end:"2027-10-09"});
assert.ok(find("international-sawfish-day").detailUrl && find("snow-leopard-day").detailUrl);
console.log("PASS: 124 events, source/date coverage, yearly/moving/range/specific-year rules, 2027 calculations, and page links.");
