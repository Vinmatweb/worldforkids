import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';

const origin='http://127.0.0.1:8765';
const activeYear=new Date().getFullYear();
const activeCount=activeYear===2026?124:123;
const eventData=JSON.parse(await readFile(new URL('../data/events.json',import.meta.url),'utf8'));
assert.equal(eventData.events.length,124);
assert.equal(new Set(eventData.events.map(e=>e.id)).size,124);
assert.ok(eventData.events.every(e=>e.sourceUrl));
assert.equal(new Set(eventData.events.map(e=>e.date2026.start.slice(5,7))).size,12);
const browser=await chromium.launch({headless:true});
const errors=[];
try{
 const desktop=await browser.newContext({viewport:{width:1440,height:900}});
 const page=await desktop.newPage();
 page.on('pageerror',e=>errors.push('desktop: '+e.message));
 await page.goto(origin+'/id/',{waitUntil:'networkidle'});
 await page.waitForFunction(n=>document.querySelector('#total-count')?.textContent.startsWith(n+' událostí v roce '+new Date().getFullYear()),activeCount);
 assert.equal(await page.locator('[data-view="month"]').getAttribute('aria-pressed'),'true');
 assert.deepEqual(await page.locator('#status-filter option').evaluateAll(os=>os.map(o=>o.value)),['all','un','unesco','campaign','national','other']);
 assert.equal(await page.locator('a[lang="en"]').count(),1);
 assert.ok(await page.locator('.day-cell').count()>=28);
 await page.locator('[data-view="week"]').click();
 assert.equal(await page.locator('.day-cell').count(),7);
 await page.locator('[data-view="day"]').click();
 assert.equal(await page.locator('.day-cell').count(),1);
 await page.locator('#org-filter').selectOption('naturewatch');
 assert.match(await page.locator('#total-count').innerText(),new RegExp('^1 událost v roce '+activeYear));
 await page.locator('#status-filter').selectOption('un');
 assert.match(await page.locator('#total-count').innerText(),new RegExp('^0 událostí v roce '+activeYear));
 await page.locator('#status-filter').selectOption('all');
 await page.locator('#org-filter').selectOption('all');
 await page.locator('#today').click();
 await page.locator('[data-view="month"]').click();
 await page.locator('#prev').click();
 await page.locator('#next').click();
 assert.ok(await page.locator('#cal-grid a[href^="http"]').count()>0);
 await page.locator('a[lang="en"]').click();
 await page.waitForURL('**/id/en/');
 await page.waitForFunction(n=>document.querySelector('#total-count')?.textContent.startsWith(n+' events listed for '+new Date().getFullYear()),activeCount);
 assert.equal(await page.locator('a[lang="cs"]').count(),1);
 assert.deepEqual(await page.locator('#status-filter option').evaluateAll(os=>os.map(o=>o.value)),['all','un','unesco','campaign','national','other']);
 await page.locator('#status-filter').selectOption('unesco');
 assert.match(await page.locator('#total-count').innerText(),new RegExp('^1 event listed for '+activeYear));
 await page.close();
 const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true,deviceScaleFactor:2});
 const m=await mobile.newPage();
 m.on('pageerror',e=>errors.push('mobile: '+e.message));
 await m.goto(origin+'/id/',{waitUntil:'networkidle'});
 await m.waitForFunction(n=>document.querySelector('#total-count')?.textContent.startsWith(n+' událostí v roce '+new Date().getFullYear()),activeCount);
 assert.equal(await m.locator('[data-view="week"]').getAttribute('aria-pressed'),'true');
 assert.equal(await m.locator('.day-cell').count(),7);
 assert.equal(await m.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
 await m.locator('[data-view="month"]').click();
 assert.ok(await m.locator('.day-cell').count()>=28);
 const english=await mobile.newPage();
 english.on('pageerror',e=>errors.push('english mobile: '+e.message));
 await english.goto(origin+'/id/en/',{waitUntil:'networkidle'});
 await english.waitForFunction(n=>document.querySelector('#total-count')?.textContent.startsWith(n+' events listed for '+new Date().getFullYear()),activeCount);
 assert.equal(await english.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
 await mobile.close();
 const tablet=await browser.newContext({viewport:{width:768,height:900}});
 const t=await tablet.newPage();t.on('pageerror',e=>errors.push('tablet: '+e.message));
 await t.goto(origin+'/id/',{waitUntil:'networkidle'});
 await t.waitForFunction(n=>document.querySelector('#total-count')?.textContent.startsWith(n+' událostí v roce '+new Date().getFullYear()),activeCount);
 assert.ok(await t.locator('.day-cell').count()>=28);
 assert.equal(await t.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
 await tablet.close();
 assert.deepEqual(errors,[]);
 await desktop.close();
 console.log('PASS: 124 events, source coverage, Czech and English calendar, views, filters, navigation, and responsive layouts at 390, 768 and 1440 px.');
}finally{await browser.close()}
