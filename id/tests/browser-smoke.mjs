import { chromium } from 'playwright';
import assert from 'node:assert/strict';

const origin='http://127.0.0.1:8765';
const activeYear=new Date().getFullYear();
const activeCount=activeYear===2026?124:123;
const browser=await chromium.launch({headless:true});
let errors=[];
try{
 const desktop=await browser.newContext({viewport:{width:1440,height:900}});
 const page=await desktop.newPage();
 page.on('pageerror',e=>errors.push('desktop: '+e.message));
 await page.goto(origin+'/id/',{waitUntil:'networkidle'});
 await page.waitForFunction(n=>document.querySelector('#total-count')?.textContent.startsWith(n+' událostí v roce '+new Date().getFullYear()),activeCount);
 assert.equal(await page.locator('[data-view="month"]').getAttribute('aria-pressed'),'true');
 assert.deepEqual(await page.locator('#status-filter option').evaluateAll(os=>os.map(o=>o.value)),['all','un','unesco','campaign','national','other']);
 assert.equal(await page.locator('a[lang="en"]').count(),1);
 assert.ok(await page.locator('.day-cell').count()>=28);
 await page.locator('[data-view="week"]').click();
 assert.equal(await page.locator('.day-cell').count(),7);
 await page.locator('[data-view="day"]').click();
 assert.equal(await page.locator('.day-cell').count(),1);
 await page.locator('#org-filter').selectOption('naturewatch');
 assert.match(await page.locator('#total-count').innerText(),new RegExp('^1 událost v roce '+activeYear));
 await page.locator('#status-filter').selectOption('un');
 assert.match(await page.locator('#total-count').innerText(),new RegExp('^0 událostí v roce '+activeYear));
 await page.locator('#status-filter').selectOption('all');
 await page.locator('#org-filter').selectOption('all');
 await page.locator('#today').click();
 await page.locator('[data-view="month"]').click();
 await page.locator('#prev').click();
 await page.locator('#next').click();
 await page.locator('a[href="./irbis/"]').first().click();
 await page.waitForURL('**/id/irbis/');
 assert.match(await page.title(),/Levhart sněžný/);
 assert.equal(await page.locator('meta[name="robots"]').getAttribute('content'),'noindex,follow');
 assert.equal(await page.locator('script[src*="googlesyndication"]').count(),0);
 await page.waitForFunction(()=>document.querySelectorAll('#activity-root .activity').length===32);
 assert.equal(await page.locator('#activity-root [data-category="coloring"] .activity').count(),5);
 assert.equal(await page.locator('#activity-root [data-category="story"] .activity').count(),12);
 assert.equal(await page.locator('#activity-root [data-category="info-card"] .activity').count(),6);
 assert.equal(await page.locator('#activity-root [data-category="tracing"] .activity').count(),9);
 assert.equal(await page.locator("#activity-root .review-status").count(),9);
 assert.match(await page.locator("#activity-root [data-category=\"tracing\"] .desc").innerText(),/LV1–LV3/);
 assert.equal(await page.locator('#activity-root a[href*="etsy"]').count(),0);
 const imageResults=await page.locator('#activity-root .activity img').evaluateAll(imgs=>Promise.all(imgs.map(async img=>{
  img.loading='eager';try{await img.decode();return img.naturalWidth>0}catch{return false}
 })));
 assert.equal(imageResults.every(Boolean),true);
 const linkStatuses=await page.locator('#activity-root .activity a').evaluateAll(links=>Promise.all(links.map(async a=>{
  const r=await fetch(a.href,{method:'HEAD'});return r.status;
 })));
 assert.deepEqual(linkStatuses,Array(32).fill(200));
 assert.equal(await page.locator('.map img').evaluate(img=>img.complete&&img.naturalWidth>0),true);
 await page.locator('a.backlink').click();
 await page.waitForURL('**/id/');
 const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true,deviceScaleFactor:2});
 const m=await mobile.newPage();
 m.on('pageerror',e=>errors.push('mobile: '+e.message));
 await m.goto(origin+'/id/',{waitUntil:'networkidle'});
 assert.equal(await m.locator('[data-view="week"]').getAttribute('aria-pressed'),'true');
 assert.equal(await m.locator('.day-cell').count(),7);
 assert.equal(await m.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
 await m.locator('[data-view="month"]').click();
 assert.ok(await m.locator('.day-cell').count()>=28);
 await m.goto(origin+'/id/irbis/',{waitUntil:'networkidle'});
 await m.waitForFunction(()=>document.querySelectorAll('#activity-root .activity').length===32);
 assert.equal(await m.locator('.map img').evaluate(img=>img.complete&&img.naturalWidth>0),true);
 assert.equal(await m.locator('meta[name="robots"]').getAttribute('content'),'noindex,follow');
 const english=await desktop.newPage();
 english.on('pageerror',e=>errors.push('english: '+e.message));
 await english.goto(origin+'/id/en/',{waitUntil:'networkidle'});
 await english.waitForFunction(n=>document.querySelector('#total-count')?.textContent.startsWith(n+' events listed for '+new Date().getFullYear()),activeCount);
 assert.deepEqual(await english.locator('#status-filter option').evaluateAll(os=>os.map(o=>o.value)),['all','un','unesco','campaign','national','other']);
 await english.locator('#status-filter').selectOption('unesco');
 assert.match(await english.locator('#total-count').innerText(),new RegExp('^1 event listed for '+activeYear));
 assert.equal(await english.locator('a[lang="cs"]').count(),1);
 await english.close();
 const tablet=await browser.newContext({viewport:{width:768,height:900}});
 const t=await tablet.newPage();t.on('pageerror',e=>errors.push('tablet: '+e.message));
 await t.goto(origin+'/id/',{waitUntil:'networkidle'});
 await t.waitForFunction(n=>document.querySelector('#total-count')?.textContent.startsWith(n+' událostí v roce '+new Date().getFullYear()),activeCount);
 assert.equal(await t.locator('[data-view="month"]').getAttribute('aria-pressed'),'true');
 assert.equal(await t.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
 await tablet.close();
 assert.deepEqual(errors,[]);
 await mobile.close();await desktop.close();
 console.log('PASS: Desktop, tablet and mobile calendar, event filters, 32 activities, working files, noindex, no ads and no JS errors.');
}finally{await browser.close()}
